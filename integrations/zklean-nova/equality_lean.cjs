// Deterministic Lean source export for the ZKL-NOVA-17 native examples.
"use strict";
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {cases,environment}=require('./equality.cjs');
const constants=Object.freeze(['Nat','Nat.zero','Nat.succ','natRec0','natRec1','natRec2','eq','refl','j0','j1','j2']);
const assert=(p,m)=>{if(!p)throw new Error(m)};

// Each source binder receives its own explicit name and type. A variable is
// resolved by its de Bruijn index, so dependent proof arguments survive export.
function term(t,scope=[]){
 assert(Array.isArray(t),'malformed source term');
 const [tag,a,b]=t;
 if(tag==='S'){assert(t.length===2&&Number.isInteger(a)&&a>=0&&a<=8,'invalid sort');return `(Sort ${a})`}
 if(tag==='C'){assert(t.length===2&&Number.isInteger(a)&&a>=0&&a<constants.length,'invalid constant');return constants[a]}
 if(tag==='B'){assert(t.length===2&&Number.isInteger(a)&&a>=0&&a<scope.length,'unbound variable');return scope[a]}
 assert(t.length===3,'invalid term arity');
 if(tag==='A')return `(${term(a,scope)} ${term(b,scope)})`;
 assert(tag==='P'||tag==='L','unsupported source term');
 const name=`x${scope.length}`,domain=term(a,scope),body=term(b,[name,...scope]);
 return tag==='P'?`((${name} : ${domain}) → ${body})`:`(fun (${name} : ${domain}) => ${body})`;
}

function render(){
 const fixtures=JSON.parse(fs.readFileSync(path.join(__dirname,'equality_fixtures.json'),'utf8'));
 assert(fixtures.length===cases.length,'fixture count drift');
 for(let i=0;i<cases.length;i++){
  const [name,proof,goal]=cases[i],f=fixtures[i];
  assert(JSON.stringify([f.name,f.proof,f.goal])===JSON.stringify([name,proof,goal]),'fixture source drift '+name);
  assert(/^[a-z][a-z0-9_]*$/.test(name),'invalid declaration name');
 }
 const digest=crypto.createHash('sha256').update(JSON.stringify({environment,cases})).digest('hex');
 const lines=[
  '-- Generated by equality_lean.cjs from the native fixed environment and fixture ASTs.',
  '-- Target toolchain: Lean 4.24.0. Run `node equality_lean.cjs --check` to verify this file.',
  '-- Lean checks the exported declarations with its own kernel semantics.',
  '-- The native certificate verifier does not parse Lean source or import Lean declarations.',
  `-- Source AST SHA-256: ${digest}`,
  'import Init',
  '',
  'set_option autoImplicit false',
  'set_option maxRecDepth 4096',
  '',
  'namespace ZkLeanEquality',
  '',
  '-- Explicit argument wrappers match the native constant IDs and finite universes.',
  '-- 0 = Nat, 1 = Nat.zero, 2 = Nat.succ.',
 ];
 for(const v of [0,1,2])lines.push(
  `-- ${3+v}: Nat elimination into Sort ${v}.`,
  `def natRec${v} (M : Nat → Sort ${v}) (z : M Nat.zero)`,
  '    (s : (n : Nat) → M n → M (Nat.succ n)) (n : Nat) : M n :=',
  '  @Nat.rec M z s n',
  ''
 );
 lines.push(
  '-- 6: Propositional equality on carriers in Sort 1.',
  'def eq (A : Sort 1) (x y : A) : Sort 0 := @Eq A x y',
  '',
  '-- 7: Reflexivity with the carrier supplied explicitly.',
  'def refl (A : Sort 1) (x : A) : eq A x x := @Eq.refl A x',
  ''
 );
 for(const v of [0,1,2])lines.push(
  `-- ${8+v}: Based path induction into Sort ${v}, including the proof in the motive.`,
  `def j${v} (A : Sort 1) (x : A) (M : (y : A) → eq A x y → Sort ${v})`,
  '    (d : M x (refl A x)) (y : A) (p : eq A x y) : M y p :=',
  '  @Eq.rec A x M d y p',
  ''
 );
 lines.push('-- Check every wrapper against the exact exported native signature.');
 for(let i=0;i<environment.length;i++)lines.push(`example : ${term(environment[i])} := ${constants[i]}`);
 lines.push('');
 for(const [name,proof,goal] of cases)lines.push(
  `-- Native fixture: ${name}.`,
  `def ${name} :`,
  `    ${term(goal)} :=`,
  `  ${term(proof)}`,
  `#print axioms ${name}`,
  ''
 );
 lines.push('end ZkLeanEquality','');
 return lines.join('\n');
}

module.exports={term,render,constants};
if(require.main===module){
 const text=render();
 if(process.argv.includes('--check')){
  const target=path.join(__dirname,'EqualityTransport.lean');
  assert(fs.readFileSync(target,'utf8')===text,'generated Lean source drift');
  console.log(JSON.stringify({lean_source:'EqualityTransport.lean',declarations:cases.length,signatures:environment.length,source_matches:true}));
 }else process.stdout.write(text);
}
