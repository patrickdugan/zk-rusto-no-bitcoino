"""Bounded grouped-AB body inventory; never constructs graphs or executes Script."""
from hashlib import sha256
from pathlib import Path
import argparse
import json
import shutil
import subprocess

from convolution import compile_convolution_predicate
from grouped_convolution import KIND, bounded_body_inventory
from script import P, Q


ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / 'grouped-convolution-oracle/src/body_pins.rs'
SOURCE_FILES = ('convolution.py', 'compact.py', 'script.py', 'wots_graph.py',
                'trace_kernels.py', 'grouped_convolution.py')


def _array(values):
    return '&[' + ', '.join(map(str, values)) + ']'


def render():
    """Four frozen row bodies plus 26 bounded body hashes, no source factory."""
    rows = bounded_body_inventory()
    assert len(rows) == 26
    frozen = []
    for count in range(1, 5):
        old = compile_convolution_predicate(P, 'conv_ab', (count,))
        assert old == compile_convolution_predicate(Q, 'conv_ab', (count,))
        assert 0 < len(old) <= 20000
        frozen.append(old)
    lines = [
        '//! Verifier-owned grouped arithmetic body pins and frozen row bytes.',
        '//! Generated by grouped_body_pins.py using bounded templates only.',
        '//! No graph construction, execution, keys or proving.',
        '//! Compiler-output provenance is not independent semantic proof.',
    ]
    for filename in SOURCE_FILES:
        raw = (ROOT / filename).read_bytes().replace(b'\r\n', b'\n')
        lines.append(f'//! Source {filename}: {sha256(raw).hexdigest()}')
    lines.extend([
        '',
        'use bitvm2_nova_script_oracle::wots::Result;',
        '',
        'struct Pin {',
        "    role: &'static str,",
        "    args: &'static [i64],",
        "    aliases: &'static [usize],",
        "    sha256: &'static str,",
        '}',
        '',
        'fn validate(role: &str, args: &[i64]) -> Result<()> {',
        '    if !matches!(role, "pallas_base" | "vesta_base")',
        '        || !matches!(args, [1, 2, 3, 4] | [4, 4, 4, 4] | [3, 2, 1]) {',
        '        return Err("closed grouped arithmetic role/count pattern required".into());',
        '    }',
        '    Ok(())',
        '}',
        '',
        'pub fn frozen_row_body(count: usize) -> Result<Vec<u8>> {',
        '    let row = count.checked_sub(1).and_then(|index| ROWS.get(index))',
        '        .ok_or("frozen conv_ab count must be1..4")?;',
        '    Ok(hex::decode(row)?)',
        '}',
        '',
        "pub fn expected_raw_body_sha256(role: &str, args: &[i64]) -> Result<&'static str> {",
        '    validate(role, args)?;',
        '    PINS.iter().find(|pin| pin.role == role && pin.args == args && pin.aliases.is_empty())',
        '        .map(|pin| pin.sha256).ok_or_else(|| "missing grouped raw body pin".into())',
        '}',
        '',
        "pub fn expected_body_sha256(role: &str, args: &[i64], aliases: &[usize]) -> Result<&'static str> {",
        '    validate(role, args)?;',
        '    let formal = args.iter().map(|count| 2 * (*count as usize) + 1).sum::<usize>();',
        '    if aliases.len() != formal || aliases.is_empty() || aliases.len() > 36 {',
        '        return Err("exact grouped formal alias framing required".into());',
        '    }',
        '    let mut next = 0usize;',
        '    for alias in aliases {',
        '        if *alias > next { return Err("first-occurrence aliases required".into()); }',
        '        if *alias == next { next += 1; }',
        '    }',
        '    if next > 15 { return Err("grouped unique operand cap exceeded".into()); }',
        '    PINS.iter().find(|pin| pin.role == role && pin.args == args && pin.aliases == aliases)',
        '        .map(|pin| pin.sha256).ok_or_else(|| "closed grouped alias body has no pin".into())',
        '}',
        '',
        'const ROWS: [&str; 4] = [',
    ])
    for raw in frozen:
        lines.append('    "' + raw.hex() + '",')
    lines.extend(['];', '', 'const PINS: &[Pin] = &['])
    for row in rows:
        role = 'pallas_base' if row['modulus'] == str(P) else 'vesta_base'
        assert row['modulus'] in (str(P), str(Q))
        alias = () if row['aliases'] is None else row['aliases']
        lines.append('    Pin { role: "' + role + '", args: ' + _array(row['argument'])
                     + ', aliases: ' + _array(alias) + ', sha256: "' + row['sha256'] + '" },')
    lines.extend(['];', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--rustfmt', default=shutil.which('rustfmt'))
    args = parser.parse_args()
    formatter = args.rustfmt
    if formatter is None:
        raise ValueError('rustfmt is required for deterministic bounded Rust pin formatting')
    formatted = subprocess.run([formatter, '--edition', '2021', '--config',
        'skip_children=true', '--emit', 'stdout'], input=render().encode('ascii'),
        capture_output=True, check=True, timeout=30)
    raw = formatted.stdout.replace(b'\r\n', b'\n')
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.is_symlink() or OUTPUT.read_bytes().replace(b'\r\n', b'\n') != raw:
            raise ValueError('grouped body pins differ from the bounded source inventory')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(raw)
    print(json.dumps(dict(schema='bitvm2-nova-grouped-body-pins/v1', kind=KIND,
        bytes=len(raw), sha256=sha256(raw).hexdigest(), frozen_rows=4, bounded_hashes=26,
        graph_calls=0, script_calls=0, key_calls=0, proving_jobs=0)))


if __name__ == '__main__':
    main()
